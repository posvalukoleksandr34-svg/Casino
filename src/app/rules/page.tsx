import Link from 'next/link';
import { GameGlyph } from '@/components/games/game-glyph';
import { Card, CardBody, CardHeader } from '@/components/ui/card';
import { PageHeader } from '@/components/ui/misc';
import { Table, Td, Th, Tr } from '@/components/ui/table';
import { listGames } from '@/server/games/lobby';

export const metadata = { title: 'Rules & odds' };

export default async function RulesPage() {
  const games = await listGames();
  return (
    <>
      <PageHeader
        eyebrow="Rules & odds"
        title="Published mathematics"
        subtitle="Return to player (RTP) is the long-run average fraction of stakes paid back, including the returned stake. House edge = 1 − RTP. Both describe averages over very many rounds; any single session can be far above or below."
      />
      <Card>
        <CardHeader title="At a glance" />
        <CardBody>
          <Table>
            <thead>
              <tr>
                <Th>Game</Th>
                <Th className="text-right">RTP</Th>
                <Th className="text-right">House edge</Th>
                <Th>Method</Th>
                <Th />
              </tr>
            </thead>
            <tbody>
              {games.map((g) => (
                <Tr key={g.id}>
                  <Td>
                    <div className="flex items-center gap-3">
                      <GameGlyph id={g.id} className="size-8" />
                      <span className="font-medium text-ink-100">{g.name}</span>
                    </div>
                  </Td>
                  <Td className="num text-right text-gold-300">{(g.theoretical.rtp * 100).toFixed(3)}%</Td>
                  <Td className="num text-right">{(g.theoretical.houseEdge * 100).toFixed(3)}%</Td>
                  <Td className="text-ink-400">
                    {g.theoretical.method === 'exact' ? 'Exact (analytical)' : `Simulation estimate${g.theoretical.ci95 ? `, 95% CI ${(g.theoretical.ci95[0] * 100).toFixed(2)}–${(g.theoretical.ci95[1] * 100).toFixed(2)}%` : ''}`}
                  </Td>
                  <Td className="text-right">
                    <Link href={`/rules/${g.id}`} className="text-sm text-gold-400 hover:text-gold-300">
                      Full rules →
                    </Link>
                  </Td>
                </Tr>
              ))}
            </tbody>
          </Table>
        </CardBody>
      </Card>
      <Card className="mt-6">
        <CardHeader title="How payouts are settled" />
        <CardBody className="grid gap-4 text-sm leading-relaxed text-ink-300 md:grid-cols-2">
          <p>Amounts are tracked in hundredths of a chip. Where a multiplier produces fractions of 0.01 chip, the payout is rounded down; this is included in the published RTP figures and changes them by less than 0.01 percentage points.</p>
          <p>Each round has a maximum potential payout and each table has stake limits. Wagers that exceed a limit are rejected before the round starts — outcomes and payouts are never changed afterwards, and never depend on who you are or how you have been doing.</p>
          <p>Your stake leaves your balance when the wager is accepted and is held in escrow until the round settles. A void (for example during a technical incident) returns the full stake.</p>
          <p>Results are generated by the server from your provably fair seeds. Animations only illustrate the recorded result. See <Link href="/fairness" className="text-gold-400">fairness</Link> to verify any round.</p>
        </CardBody>
      </Card>
    </>
  );
}
